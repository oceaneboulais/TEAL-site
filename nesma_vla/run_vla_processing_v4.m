                        saveas(gcf,fullfile(savefolder,[png_savename '.fig']))
                    end
                    set(groot,'CurrentFigure',el_hist_fig); clf;
                end


            if save_to_ppt
                newFile = pptx.save(fullfile(savefolder,'directional_histograms'));
            end
            
        end
