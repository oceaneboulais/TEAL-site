                        fprintf('Added slide %d\n',slideId);
                        pptx.addTextbox([title_slide ' ' subtitle_slide sprintf(' %1.0f kHz to %1.0f kHz',f1/1e3,f2/1e3)]);
                        pptx.addPicture(gcf);
