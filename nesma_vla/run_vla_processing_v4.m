    datasubdir = fullfile(data_basedir,expt_name,event_name);

    savefolder = fullfile(procdata_basedir,mfilename,...
        sprintf('%s_fs%1.0f_nfft%1.0f_noverlp%1.0f_dEL%i',array_type,fs,nfft,noverlp,el_res),...
       expt_name,event_name);

    if ~isfolder(savefolder)
        mkdir(savefolder)
    end

    % load the USBL data
%     driftcam = loadDrifterLogDataV2([t0_utc tend_utc],fullfile(datasubdir,'ControlSystem'),drifter_num);
    data_dir = fullfile(data_basedir,expt_name,'AcousticData',event_name);
%     [filelist,filetimes_utc] = getFilesInRange(data_dir,t0_utc,tend_utc);
    filelist_full = dir(fullfile(data_dir,'*.sio'));
%     logdir = fullfile(data_basedir,data_subdir,'ControlSystem');
    filenames_full = vertcat(filelist_full.name);
    % Extract parts
%     timenames = extractBetween(filenames,'.','.');
    YYYY = 2000+str2num(filenames_full(:,8+(1:2)));      % Extract full 4-digit year
    DDD = str2num(filenames_full(:,8+(3:5)));       % Extract Julian day
    HH = str2num(filenames_full(:,8+(6:7)));        % Extract Hour
    MM = str2num(filenames_full(:,8+(8:9)));      % Extract Minute
    SS = str2num(filenames_full(:,8+(10:11)));      % Extract Second

    % Convert Julian day to datetime
    filetimes_utc = datetime(YYYY, 1, 1, HH, MM, SS) + days(DDD - 1);

    if ~isempty(time_to_process)
        include_files = filetimes_utc >=time_to_process(1) & filetimes_utc <= time_to_process(2);
    else
        include_files = true(size(filetimes_utc));
    end

    filetimes_utc = filetimes_utc(include_files);
    filenames_full = filenames_full(include_files);
    filelist_full = filelist_full(include_files);

    t0_utc = filetimes_utc(1);
    tend_utc = filetimes_utc(end);
    
    acoustic_dir = fullfile(datasubdir,'AcousticData');
    acoustic_files = dir(fullfile(acoustic_dir,'drifter*.wav'));

    config_file = dir(fullfile(data_dir,'acoustic_config_*.txt'));
    config_file = fullfile(config_file.folder,config_file.name);
    acoustic_config = readtable(config_file);
    acoustic_config = acoustic_config(ch_select,:);

%     for di = dive_index
        T_utc_save = [];

%         dive_time_start_utc = driftlog.TimeLastSatUTC(di);
%         if isnat(dive_time_start_utc)&& di==min(dive_index)
%             dive_time_start_utc = driftlog.DeployTimeUTC(di);
%         end
%         dive_time_stop_utc = driftlog.TimeFirstSatUTC(di);
%         if isnat(dive_time_stop_utc) && di==max(dive_index)
%             % if there was no dive end time, just use the recover time
%             dive_time_stop_utc = driftlog.RecoverTimeUTC(di);
%         end

%         vector_sensor = driftlog.VectorSensor{di};
%         acoustic_num = driftlog.AcousticSphere(di);

        

        
        dive_duration_hrs = hours(tend_utc - t0_utc);
        if  dive_duration_hrs > max_plot_time_hrs 
            % this plot and histogram object will be too large, split it up
            % into parts to process separately 
            Nparts = ceil(dive_duration_hrs/max_plot_time_hrs);
            parts_time_start_utc = t0_utc + hours(max_plot_time_hrs*(0:(Nparts-1)));
            parts_time_stop_utc = t0_utc + hours(max_plot_time_hrs*(1:(Nparts-1)));
            % the last time should alwasy be the end of the dive
            parts_time_stop_utc = [parts_time_stop_utc tend_utc];
        else 
            Nparts = 1;
            parts_time_start_utc = t0_utc;
            parts_time_stop_utc = tend_utc;
        end
        for ni = 1:Nparts
            
            time_start_utc = parts_time_start_utc(ni);
            time_stop_utc = parts_time_stop_utc(ni);

            this_event_name = sprintf('VLA_Deployment_%i_%s_%s',deployment,...
                datestr(time_start_utc,'YYYYmmDDThhMMss'),...
                datestr(time_stop_utc,'YYYYmmDDThhMMss'));

            bf_hist_filename = fullfile(savefolder,[this_event_name '_bf_hist.mat']);
%             avs_hist_filename = fullfile(savefolder,[this_event_name '_avs_hist.mat']);
        
%        [filelist,file_time_utc,filenames] = getFilesInRange(acoustic_files,time_start_utc,time_stop_utc);
          in_range = filetimes_utc>=time_start_utc & filetimes_utc<= time_stop_utc;
          filelist = filelist_full(in_range);
          file_time_utc = filetimes_utc(in_range);
          filenames = filenames_full(in_range,:);
            Nfiles = length(filelist);


%         azi_hist = zeros(Nfiles,length(hist_param.az_edges)-1,size(fband,1));
        elev_hist = single(zeros(Nfiles,length(hist_param.el_edges)-1,size(fband,1)));
        t_utc = NaT(1,Nfiles);

        tabs_files=datenum(file_time_utc);  %%%ALISON, CAN YOU FIX THIS?

        % now loop through the files found for this dive
        for file_idx = 1:Nfiles
            tic
            fprintf('\nProcessing file %i of %i: %s\n',file_idx,Nfiles,filelist(file_idx).name)

            bfsavename = sprintf('beamformer_data_%s.mat',datestr(file_time_utc(file_idx),'yyyymmddTHHMMSS'));
            bfsavename = fullfile(savefolder,'beamformer_data',bfsavename);
            bffile_exists = exist(bfsavename,'file');

%             vssavename = sprintf('avs_data_%s.mat',datestr(file_time_utc(file_idx),'yyyymmddTHHMMSS'));
%             vssavename = fullfile(savefolder,'avs_data',vssavename);
%             vsfile_exists = exist(vssavename,'file');

            if ~isfolder(fullfile(savefolder,'beamformer_data'))
                mkdir(fullfile(savefolder,'beamformer_data'))
            end
%             if ~isfolder(fullfile(savefolder,'avs_data'))
%                 mkdir(fullfile(savefolder,'avs_data'))
%             end

            % only load the data if we are going to process or reprocess
            if (do_processing&&((~bffile_exists||overwrite_beam_data)))
                % load the data and process
                fprintf('Loading data..\n')

                filename = fullfile(fullfile(filelist(file_idx).folder,filelist(file_idx).name));
                try
                    y = sioread(filename,1,0,ch_select);
                    fs00 = 25e3;
                catch
                    warning('Error reading file, skipping file %s',filename)
                    continue
                end
                disp('Data loaded');
                toc

%                 t_utc = file_time_utc(file_idx):seconds((1/fs00)):(file_time_utc(file_idx) + seconds(size(y0,1)-1)/fs00);
%                 t_sec0 = convertTo(t_utc,'posixtime'); %t_sec = t_sec - t_sec(1);

                if do_resample
                    %tic
                    % [y,t_sec] = resample(y0,t_sec0,fs);
                    % toc
                    disp('Decimation started')

                    R=round(fs00/fs);
                    sizz=size(y0);
                    sizz(1)=floor(sizz(1)/2);
                    for II=1:sizz(2)
                        y(:,II)=decimate(y0(:,II),R);
                    end
                    disp('Decimation done')
                    toc

                    clear y0 
                else
                    if fs00~=fs
                        error("wrong sample rate!")
                    end
                end
                if do_filter
                    [bb,aa]= butter(2,2*[f1 f2]/fs);
                    y = filter(bb,aa,y);

                end

                % compute the spectrogram of each channel
                k = 0;
				disp('compute FFT')
                [S,F,T,~,~,pos] = getDrifterSpectrogramV2(y,nfft,noverlp,fs,acoustic_config,'stft');
				disp('FFT done')
                toc
                T_utc = file_time_utc(file_idx) + seconds(T);

                clear y

            end

            %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
            %%%%%%Vertical beamforming option%%%%%%%%%%
            %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
            if bffile_exists&&do_processing
                fprintf('Beamform Data Exists in: %s\n',bfsavename)
            end
            % if the file doesn't exist, or if we are overwriting the data
            % run the freq domain beamformer
            if do_processing&&(~bffile_exists||overwrite_beam_data)
                fprintf('Running Beamformer: %s\n',bfsavename)

%                 switch array_type
%                     case 'line'
% %                         bf_array_idx = [1 4 5 6 7 8];
%                         bf_array_idx = 1:size(S,3);
%                     otherwise
%                         error('Array type not defined')
%                 end

                %%%AARON: remove frequencies we don't care about.
                if only_bf_bands 
                    Ifreq=[];
                    for Iband=1:size(fband,1)
                        Ifreq=[Ifreq; find(F>=fband(Iband,1)&F<=fband(Iband,2))];
                    end
                    Ifreq=unique(Ifreq);  %Remove overlaps between frequency bands;
                else
                    Ifreq = 1:length(F);
                end
             
                %%%Run conventional beamformer, averaging over time_avg
                %%%intervals in time, and summing over frequency_bands
                %%%defined by fband
                [B_pow,Fout,Tout] = beamform_from_spec_avg(...
                    S(Ifreq,:,:),T,F(Ifreq),0,elev_deg,...
                    pos,[],bf_fband,time_avg);

                beamdata.kscale = 100;
                beamdata.B_pow_dB = uint16(beamdata.kscale*10*log10(B_pow));
                beamdata.F=Fout;
                beamdata.T_utc = file_time_utc(file_idx) + seconds(Tout);
                beamdata.elev_deg = elev_deg;

                toc
                disp('Beamformer done.')
                
                if save_data
                    disp('Saving beamformer data...')
                    save(bfsavename,'beamdata')
                    disp('Save complete.')
                    toc
                end

            elseif do_stats&&do_processing&&bffile_exists&&(~exist(bf_hist_filename,'file')||overwrite_stats)
                disp('Loading beamformer data...')
                load(bfsavename,'beamdata');
                toc
                disp('Load complete.')
            end  %%Beamforming

            %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
            %%%%%%%%%vector_sensor_processing
            %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
            
           

            %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
            %%%%%Accumlated statistics from raw metrics%%%
            %%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

            
            if do_stats
                if do_processing&&(overwrite_stats||~exist(bf_hist_filename,'file'))
                    disp('Starting beamformer histogram processing...')
                    if bffile_exists&&~overwrite_beam_data
                        % we need to get the power in linear units if we
                        % don't already have it in memory
                        if ~isfield(beamdata,'kscale')
                            beamdata.kscale = 1;
                        end
                        B_pow = 10.^(double(beamdata.B_pow_dB)/(beamdata.kscale*10));
                    end
                    bin_width = median(diff(hist_param.el_edges));
                    el_centers = hist_param.el_edges(1:end-1)+bin_width/2;
                    for iband = 1:size(fband,1)
                        f1 = fband(iband,1);
                        f2 = fband(iband,2);
        
                        fidx = (beamdata.F>=fband(iband,1))&(beamdata.F<=fband(iband,2));
                        B_incoh = squeeze(sum(B_pow(fidx,:,:)));

                        [B_ele_max,max_idx] = max(B_incoh,[],2);
                        elev_est= beamdata.elev_deg(max_idx);

                        elev_hist(file_idx,:,iband) = single(histcounts(elev_est,hist_param.el_edges,'Normalization','count')); 
                        clear B_incoh B_ele_max

                        toc
                    end
                    disp('Finished processing.')
                end

            end %do stats
            t1 = toc;
            fprintf('File took %1.2f seconds\n\n\n  ',t1)
        end %file_idx

        %%%%Save statistical data and generate histograms
        

        if do_stats
            if ~exist(bf_hist_filename,'file')||overwrite_stats
                disp('Saving beamformer histogram data...')
           
                if ~isfolder(fullfile(savefolder))
