                disp('Loading beamformer histogram data...')
                load(bf_hist_filename,'file_time_utc','hist_param','elev_hist','fband')
            end

        end

        % produce the histogram plots
        if do_histogram_plots 
            t_label = {datestr(time_start_utc,'yyyymmddTHHMMSS') datestr(time_stop_utc,'yyyymmddTHHMMSS')};

